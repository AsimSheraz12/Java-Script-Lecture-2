// Comparison Operators

let a = 5;

console.log("a == 5: " + (a == 5)); // true  " Equality operator checks if the values are equal, ignoring the type"
console.log("a != 5: " + (a != 5)); // false " Inequality operator checks if the values are not equal, ignoring the type"
console.log("a === 5: " + (a === 5)); // true " Strict equality operator checks if the values and types are equal"
console.log("a !== 5: " + (a !== 5)); // false " Strict inequality operator checks if the values or types are not equal"
console.log("a > 3: " + (a > 3)); // true " Greater than operator checks if the left operand is greater than the right operand"
console.log("a < 10: " + (a < 10)); // true " Less than operator checks if the left operand is less than the right operand"
console.log("a >= 5: " + (a >= 5)); // true " Greater than or equal operator checks if the left operand is greater than or equal to the right operand"
console.log("a <= 5: " + (a <= 5)); // true " Less than or equal operator checks if the left operand is less than or equal to the right operand"




// Logical Operators

let b = true;
let c = false;

console.log("\n\n\n");

console.log("b && c: " + (b && c)); // false " Logical AND operator returns true if both operands are true"
console.log("b || c: " + (b || c)); // true " Logical OR operator returns true if at least one operand is true"
console.log("!b: " + (!b)); // false " Logical NOT operator returns the opposite of the operand"
