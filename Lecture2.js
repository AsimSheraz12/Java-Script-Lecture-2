// Unary Operators Practice

let x = 10, y = 5;

console.log("Value of x is: " + ++x); 

/* ++x means pre-increment, it will increment the value of x by 1 and then return the value of x. */

console.log("\n"); // Move Next line

console.log("Value of y is: " + y++);

/* y++ means post-increment, it will return the value of y and then increment the value of y by 1. */

console.log("\n"); // Move Next line

console.log("Value of x is: " + --x); 

/* --x means pre-decrement, it will decrement the value of x by 1 and then return the value of x. */

console.log("\n"); // Move Next line

console.log("Value of y is: " + y--);

/* y-- means post-decrement, it will return the value of y and then decrement the value of y by 1. */