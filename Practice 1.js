// Check Multiple of 5

let number = prompt("Enter a number:"); // Prompt user to enter a number

if (number % 5 === 0)  // Check if the number is a multiple of 5
{
    console.log(number + " is a multiple of 5."); // Output if true
}
else
{
    console.log(number + " is not a multiple of 5."); // Output if false
}